import type { ReactNode } from "react";
import { useTranslation } from "react-i18next";
import type { Column, Index } from "../../api/types";
import { formatBytes, formatCount, formatTimestamp } from "../../lib/format";

/** Таблица в прокручиваемой области: широкие таблицы листаются сами, область достижима с клавиатуры. */
export function ScrollTable({ label, children }: { label: string; children: ReactNode }) {
  return (
    <div className="table-scroll" role="region" tabIndex={0} aria-label={label}>
      <table aria-label={label}>{children}</table>
    </div>
  );
}

/** Режимы хранения колонки (`attstorage`) — ключевые слова `ALTER COLUMN … SET STORAGE`, не переводятся. */
const STORAGE: Record<string, string> = { p: "PLAIN", e: "EXTERNAL", m: "MAIN", x: "EXTENDED" };

/** `GENERATED …` — слова синтаксиса SQL, не переводятся. */
function identityOrGenerated(c: Column): string | null {
  if (c.identity === "a") return "GENERATED ALWAYS AS IDENTITY";
  if (c.identity === "d") return "GENERATED BY DEFAULT AS IDENTITY";
  // Выражение генерируемой колонки лежит в defaultExpr (так его отдаёт каталог).
  if (c.generated === "s") return `GENERATED ALWAYS AS (${c.defaultExpr ?? ""}) STORED`;
  return null;
}

export function ColumnsTable({ columns }: { columns: Column[] }) {
  const { t } = useTranslation();
  if (columns.length === 0) return <p className="empty">{t("object.empty")}</p>;
  return (
    <ScrollTable label={t("object.columns")}>
      <thead>
        <tr>
          <th scope="col">{t("object.name")}</th>
          <th scope="col">{t("object.type")}</th>
          <th scope="col">{t("object.notNull")}</th>
          <th scope="col">{t("object.default")}</th>
          <th scope="col">
            {t("object.identity")} / {t("object.generated")}
          </th>
          <th scope="col">{t("object.collation")}</th>
          <th scope="col">{t("object.statTarget")}</th>
          <th scope="col">{t("object.storage")}</th>
          <th scope="col">{t("object.comment")}</th>
        </tr>
      </thead>
      <tbody>
        {columns.map((c) => {
          const special = identityOrGenerated(c);
          return (
            <tr key={c.name}>
              <td>{c.name}</td>
              <td>
                <code>{c.dataType}</code>
              </td>
              <td>{c.notNull ? t("object.yes") : t("object.no")}</td>
              {/* У генерируемой колонки выражение уже показано рядом со словами GENERATED. */}
              <td>{c.generated !== null || c.defaultExpr === null ? "—" : <code>{c.defaultExpr}</code>}</td>
              <td>{special ?? "—"}</td>
              <td>{c.collation ?? "—"}</td>
              <td>{c.statTarget === null ? "—" : formatCount(c.statTarget)}</td>
              <td>{STORAGE[c.storage] ?? c.storage}</td>
              <td>{c.comment ?? "—"}</td>
            </tr>
          );
        })}
      </tbody>
    </ScrollTable>
  );
}

export function IndexesTable({ indexes }: { indexes: Index[] }) {
  const { t } = useTranslation();
  if (indexes.length === 0) return <p className="empty">{t("object.empty")}</p>;
  return (
    <ScrollTable label={t("object.indexes")}>
      <thead>
        <tr>
          <th scope="col">{t("object.name")}</th>
          <th scope="col">{t("object.definition")}</th>
          <th scope="col">{t("object.flags")}</th>
          <th scope="col">{t("object.size")}</th>
          <th scope="col">{t("object.idxScan")}</th>
          <th scope="col">{t("object.idxTupRead")}</th>
          <th scope="col">{t("object.lastIdxScan")}</th>
        </tr>
      </thead>
      <tbody>
        {indexes.map((ix) => (
          // Невалидный индекс (прерванный CREATE INDEX CONCURRENTLY) не используется планировщиком — строка выделена.
          <tr key={ix.name} className={ix.valid ? undefined : "invalid"}>
            <td>{ix.name}</td>
            <td>
              <code>{ix.definition}</code>
            </td>
            <td>
              <span className="badges">
                {ix.primary && <span className="kind-badge">{t("object.primary")}</span>}
                {ix.unique && !ix.primary && <span className="kind-badge">{t("object.unique")}</span>}
                {!ix.valid && <span className="kind-badge invalid">{t("object.invalid")}</span>}
              </span>
            </td>
            <td>{formatBytes(ix.sizeBytes)}</td>
            <td>{formatCount(ix.idxScan)}</td>
            <td>{formatCount(ix.idxTupRead)}</td>
            <td>{formatTimestamp(ix.lastIdxScanMs)}</td>
          </tr>
        ))}
      </tbody>
    </ScrollTable>
  );
}
